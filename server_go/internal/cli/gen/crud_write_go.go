package gen

import (
	"fmt"
	"io"
	"strings"
)

// WriteCrudGoHandlers 写入 admin 或插件 HTTP 包内的 CRUD 函数（仅 admin 路由风格）。
func WriteCrudGoHandlers(w io.Writer, b *CrudBundle) error {
	if b.IsPlugin {
		return writePluginHandlers(w, b)
	}
	return writeCoreHandlers(w, b)
}

func crudNeedTimeImport(b *CrudBundle) bool {
	for _, f := range b.BodyFields {
		if f.ParseTime {
			return true
		}
	}
	return false
}

func writeCoreHandlers(w io.Writer, b *CrudBundle) error {
	ind := "\t\t"
	needDatatypes := false
	for _, bf := range b.BodyFields {
		if bf.GoType == "json.RawMessage" {
			needDatatypes = true
			break
		}
	}
	var sb strings.Builder
	sb.WriteString("// Code generated by fastapp-cli gen crud; edit MenuPerm / routes as needed.\n")
	sb.WriteString("package admin\n\nimport (\n")
	sb.WriteString("\t\"strconv\"\n\t\"strings\"\n")
	if crudNeedTimeImport(b) {
		sb.WriteString("\t\"time\"\n")
	}
	if needDatatypes {
		sb.WriteString("\t\"gorm.io/datatypes\"\n")
	}
	m := b.ModulePath
	sb.WriteString(fmt.Sprintf("\n\ttools %q\n", JoinImport(m, "internal/app/common")))
	sb.WriteString(fmt.Sprintf("\t%q\n", JoinImport(m, "internal/app/common/deps")))
	sb.WriteString(fmt.Sprintf("\t%q\n", JoinImport(m, "internal/app/model")))
	sb.WriteString(fmt.Sprintf("\t%q\n", JoinImport(m, "internal/app/common/response")))
	sb.WriteString("\t\"github.com/gin-gonic/gin\"\n)\n\n")

	bodyName := LowerFirst(b.StructName) + "CrudBody"
	writeBodyStruct(&sb, bodyName, b)

	sb.WriteString(fmt.Sprintf("func %sList(d *deps.Deps) gin.HandlerFunc {\n", b.StructName))
	sb.WriteString("\treturn deps.Bind(d, func(h *deps.HandlerCtx) {\n")
	writeListBody(&sb, b, ind)
	sb.WriteString("\t})\n}\n\n")

	sb.WriteString(fmt.Sprintf("func %sCreate(d *deps.Deps) gin.HandlerFunc {\n", b.StructName))
	sb.WriteString("\treturn deps.Bind(d, func(h *deps.HandlerCtx) {\n")
	writeCreateBody(&sb, b, bodyName, "model", false, ind)
	sb.WriteString("\t})\n}\n\n")

	sb.WriteString(fmt.Sprintf("func %sSave(d *deps.Deps) gin.HandlerFunc {\n", b.StructName))
	sb.WriteString("\treturn deps.Bind(d, func(h *deps.HandlerCtx) {\n")
	writeSaveBody(&sb, b, bodyName, "model", false, ind)
	sb.WriteString("\t})\n}\n\n")

	sb.WriteString(fmt.Sprintf("func %sDelete(d *deps.Deps) gin.HandlerFunc {\n", b.StructName))
	sb.WriteString("\treturn deps.Bind(d, func(h *deps.HandlerCtx) {\n")
	writeDeleteBody(&sb, b, "model", ind)
	sb.WriteString("\t})\n}\n")

	_, err := w.Write([]byte(sb.String()))
	return err
}

func writePluginHandlers(w io.Writer, b *CrudBundle) error {
	ind := "\t"
	alias := b.ModelPkgAlias
	needDatatypes := false
	for _, bf := range b.BodyFields {
		if bf.GoType == "json.RawMessage" {
			needDatatypes = true
			break
		}
	}
	var sb strings.Builder
	sb.WriteString("// Code generated by fastapp-cli gen crud.\n")
	sb.WriteString("package " + b.HandlerPackage + "\n\nimport (\n")
	sb.WriteString("\t\"strconv\"\n\t\"strings\"\n")
	if crudNeedTimeImport(b) {
		sb.WriteString("\t\"time\"\n")
	}
	if needDatatypes {
		sb.WriteString("\t\"gorm.io/datatypes\"\n")
	}
	m := b.ModulePath
	sb.WriteString(fmt.Sprintf("\n\ttools %q\n", JoinImport(m, "internal/app/common")))
	sb.WriteString(fmt.Sprintf("\t%q\n", JoinImport(m, "internal/app/common/deps")))
	sb.WriteString(fmt.Sprintf("\t%q\n", JoinImport(m, "internal/app/middleware")))
	sb.WriteString(fmt.Sprintf("\t%q\n", JoinImport(m, "internal/app/common/response")))
	sb.WriteString(fmt.Sprintf("\t%s %q\n", alias, b.ModelImport))
	sb.WriteString(")\n\n")

	base := b.handlerPluginBase()
	bodyName := base + "Body"
	writeBodyStruct(&sb, bodyName, b)

	sb.WriteString(fmt.Sprintf("func %sList(h *deps.HandlerCtx) {\n", base))
	writeListBody(&sb, b, ind)
	sb.WriteString("}\n\n")

	sb.WriteString(fmt.Sprintf("func %sCreate(h *deps.HandlerCtx) {\n", base))
	writeCreateBody(&sb, b, bodyName, alias, true, ind)
	sb.WriteString("}\n\n")

	sb.WriteString(fmt.Sprintf("func %sSave(h *deps.HandlerCtx) {\n", base))
	writeSaveBody(&sb, b, bodyName, alias, true, ind)
	sb.WriteString("}\n\n")

	sb.WriteString(fmt.Sprintf("func %sDelete(h *deps.HandlerCtx) {\n", base))
	writeDeleteBody(&sb, b, alias, ind)
	sb.WriteString("}\n")

	_, err := w.Write([]byte(sb.String()))
	return err
}

func writeBodyStruct(sb *strings.Builder, name string, b *CrudBundle) {
	sb.WriteString("type " + name + " struct {\n")
	for _, f := range b.BodyFields {
		sb.WriteString(fmt.Sprintf("\t%s %s `json:\"%s\"`\n", f.GoName, f.GoType, f.JSONName))
	}
	sb.WriteString("}\n\n")
}

func writeListBody(sb *strings.Builder, b *CrudBundle, ind string) {
	sb.WriteString(ind + "page, pageSize := tools.ParsePage(h.C)\n")
	sb.WriteString(fmt.Sprintf(ind+"tbl := (&%s.%s{}).TableName()\n", b.ModelPkgAliasOrModel(), b.StructName))
	sb.WriteString(fmt.Sprintf(ind+"q := h.D.DBx(h.C).Model(&%s.%s{})\n", b.ModelPkgAliasOrModel(), b.StructName))
	if b.HasDeletedAt {
		sb.WriteString(ind + "q = q.Where(tbl + \".deleted_at IS NULL\")\n")
	}
	for _, q := range b.QueryFields {
		switch q.QueryMode {
		case "like":
			sb.WriteString(fmt.Sprintf(ind+"if v := strings.TrimSpace(h.C.Query(\"%s\")); v != \"\" {\n", q.DBName))
			sb.WriteString(fmt.Sprintf(ind+"\tq = q.Where(tbl+\".%s LIKE ?\", \"%%\"+v+\"%%\")\n", q.DBName))
			sb.WriteString(ind + "}\n")
		case "eq_int":
			sb.WriteString(fmt.Sprintf(ind+"if v := strings.TrimSpace(h.C.Query(\"%s\")); v != \"\" {\n", q.DBName))
			sb.WriteString(ind + "\tif n, err := strconv.Atoi(v); err == nil {\n")
			sb.WriteString(fmt.Sprintf(ind+"\t\tq = q.Where(tbl+\".%s = ?\", n)\n", q.DBName))
			sb.WriteString(ind + "\t}\n" + ind + "}\n")
		default:
			sb.WriteString(fmt.Sprintf(ind+"if v := strings.TrimSpace(h.C.Query(\"%s\")); v != \"\" {\n", q.DBName))
			sb.WriteString(fmt.Sprintf(ind+"\tq = q.Where(tbl+\".%s = ?\", v)\n", q.DBName))
			sb.WriteString(ind + "}\n")
		}
	}
	sb.WriteString(ind + "if ob := strings.TrimSpace(h.C.Query(\"order_by\")); ob != \"\" {\n")
	sb.WriteString(ind + "\tdir := strings.TrimSpace(h.C.Query(\"order_by_direction\"))\n")
	sb.WriteString(ind + "\tif dir != \"asc\" {\n" + ind + "\t\tdir = \"desc\"\n" + ind + "\t}\n")
	sb.WriteString(ind + "\tq = q.Order(tbl + \".\" + ob + \" \" + dir)\n")
	sb.WriteString(ind + "} else {\n")
	sb.WriteString(fmt.Sprintf(ind+"\tq = q.Order(tbl + \".%s DESC\")\n", b.PrimaryKey))
	sb.WriteString(ind + "}\n")
	sb.WriteString(ind + "var total int64\n")
	sb.WriteString(ind + "if err := q.Count(&total).Error; err != nil {\n")
	sb.WriteString(ind + "\tresponse.JSON(h.C, 200, response.Fail(\"count failed\"))\n")
	sb.WriteString(ind + "\treturn\n" + ind + "}\n")
	sb.WriteString(ind + "offset := (page - 1) * pageSize\n")
	sb.WriteString(fmt.Sprintf(ind+"var rows []%s.%s\n", b.ModelPkgAliasOrModel(), b.StructName))
	sb.WriteString(ind + "if err := q.Limit(pageSize).Offset(offset).Find(&rows).Error; err != nil {\n")
	sb.WriteString(ind + "\tresponse.JSON(h.C, 200, response.Fail(\"query failed\"))\n")
	sb.WriteString(ind + "\treturn\n" + ind + "}\n")
	sb.WriteString(ind + "response.JSON(h.C, 200, response.OK(map[string]any{\"list\": rows, \"total\": total}))\n")
}

// ModelPkgAliasOrModel 生成 list 等处引用包名（core 用 model）。
func (b *CrudBundle) ModelPkgAliasOrModel() string {
	if b.IsPlugin {
		return b.ModelPkgAlias
	}
	return "model"
}

func writeCreateBody(sb *strings.Builder, b *CrudBundle, bodyName, pkgAlias string, plugin bool, ind string) {
	sb.WriteString(fmt.Sprintf(ind+"var body %s\n", bodyName))
	sb.WriteString(ind + "if !tools.BindJSONOr422(h.C, &body) {\n" + ind + "\treturn\n" + ind + "}\n")
	if plugin && b.HasCreatedBy {
		sb.WriteString(ind + "uid := middleware.UserID(h.C)\n" + ind + "cb := int64(uid)\n")
	}
	sb.WriteString(fmt.Sprintf(ind+"row := %s.%s{}\n", pkgAlias, b.StructName))
	for _, f := range b.BodyFields {
		assignCreateField(sb, f, ind)
	}
	if plugin && b.HasCreatedBy {
		sb.WriteString(ind + "row.CreatedBy = &cb\n" + ind + "row.UpdatedBy = &cb\n")
	}
	sb.WriteString(ind + "if err := h.D.DBx(h.C).Create(&row).Error; err != nil {\n")
	sb.WriteString(ind + "\tresponse.JSON(h.C, 200, response.Fail(\"create failed\"))\n")
	sb.WriteString(ind + "\treturn\n" + ind + "}\n")
	sb.WriteString(ind + "response.JSON(h.C, 200, response.OK(nil))\n")
}

func assignCreateField(sb *strings.Builder, f CrudBodyField, ind string) {
	switch {
	case f.GoType == "json.RawMessage":
		sb.WriteString(fmt.Sprintf(ind+"if len(body.%s) > 0 {\n"+ind+"\trow.%s = datatypes.JSON(body.%s)\n"+ind+"}\n", f.GoName, f.GoName, f.GoName))
	case f.ParseTime:
		gn := f.GoName
		sb.WriteString(fmt.Sprintf(ind+"if body.%s != nil && strings.TrimSpace(*body.%s) != \"\" {\n", gn, gn))
		sb.WriteString(fmt.Sprintf(ind+"\tif t, err := time.ParseInLocation(\"2006-01-02 15:04:05\", strings.TrimSpace(*body.%s), time.Local); err == nil {\n", gn))
		sb.WriteString(fmt.Sprintf(ind+"\t\trow.%s = t\n", gn))
		sb.WriteString(ind + "\t} else if t2, err2 := time.ParseInLocation(\"2006-01-02\", strings.TrimSpace(*body." + gn + "), time.Local); err2 == nil {\n")
		sb.WriteString(fmt.Sprintf(ind+"\t\trow.%s = t2\n", gn))
		sb.WriteString(ind + "\t}\n" + ind + "}\n")
	default:
		if strings.HasPrefix(f.GoType, "*") {
			modelPtr := f.ModelGoType == "" || strings.HasPrefix(f.ModelGoType, "*")
			if modelPtr {
				sb.WriteString(fmt.Sprintf(ind+"if body.%s != nil {\n"+ind+"\trow.%s = body.%s\n"+ind+"}\n", f.GoName, f.GoName, f.GoName))
			} else {
				sb.WriteString(fmt.Sprintf(ind+"if body.%s != nil {\n"+ind+"\trow.%s = *body.%s\n"+ind+"}\n", f.GoName, f.GoName, f.GoName))
			}
		} else {
			sb.WriteString(fmt.Sprintf(ind+"row.%s = body.%s\n", f.GoName, f.GoName))
		}
	}
}

func writeSaveBody(sb *strings.Builder, b *CrudBundle, bodyName, pkgAlias string, plugin bool, ind string) {
	sb.WriteString(ind + "id, ok := tools.ParseIDParam(h.C, \"id\")\n")
	sb.WriteString(ind + "if !ok {\n" + ind + "\treturn\n" + ind + "}\n")
	sb.WriteString(fmt.Sprintf(ind+"var body %s\n", bodyName))
	sb.WriteString(ind + "if !tools.BindJSONOr422(h.C, &body) {\n" + ind + "\treturn\n" + ind + "}\n")
	if plugin && b.HasUpdatedBy {
		sb.WriteString(ind + "uid := middleware.UserID(h.C)\n" + ind + "ub := int64(uid)\n")
	}
	sb.WriteString(ind + "updates := map[string]any{}\n")
	for _, f := range b.BodyFields {
		assignUpdateMap(sb, f, ind)
	}
	if plugin && b.HasUpdatedBy {
		sb.WriteString(ind + "updates[\"updated_by\"] = ub\n")
	}
	sb.WriteString(ind + "if len(updates) == 0 {\n" + ind + "\tresponse.JSON(h.C, 200, response.OK(nil))\n" + ind + "\treturn\n" + ind + "}\n")
	sb.WriteString(fmt.Sprintf(ind+"res := h.D.DBx(h.C).Model(&%s.%s{}).Where(\"%s = ?\", id).Updates(updates)\n", pkgAlias, b.StructName, b.PrimaryKey))
	sb.WriteString(ind + "if res.Error != nil {\n" + ind + "\tresponse.JSON(h.C, 200, response.Fail(\"save failed\"))\n" + ind + "\treturn\n" + ind + "}\n")
	sb.WriteString(ind + "response.JSON(h.C, 200, response.OK(nil))\n")
}

func assignUpdateMap(sb *strings.Builder, f CrudBodyField, ind string) {
	j := f.JSONName
	gn := f.GoName
	switch {
	case f.GoType == "json.RawMessage":
		sb.WriteString(fmt.Sprintf(ind+"if len(body.%s) > 0 {\n"+ind+"\tupdates[\"%s\"] = datatypes.JSON(body.%s)\n"+ind+"}\n", gn, j, gn))
	case f.ParseTime:
		sb.WriteString(fmt.Sprintf(ind+"if body.%s != nil {\n", gn))
		sb.WriteString(fmt.Sprintf(ind+"\tif strings.TrimSpace(*body.%s) == \"\" {\n"+ind+"\t\tupdates[\"%s\"] = nil\n", gn, j))
		sb.WriteString(ind + "\t} else if t, err := time.ParseInLocation(\"2006-01-02 15:04:05\", strings.TrimSpace(*body." + gn + "), time.Local); err == nil {\n")
		sb.WriteString(fmt.Sprintf(ind+"\t\tupdates[\"%s\"] = t\n", j))
		sb.WriteString(ind + "\t} else if t2, err2 := time.ParseInLocation(\"2006-01-02\", strings.TrimSpace(*body." + gn + "), time.Local); err2 == nil {\n")
		sb.WriteString(fmt.Sprintf(ind+"\t\tupdates[\"%s\"] = t2\n", j))
		sb.WriteString(ind + "\t}\n" + ind + "}\n")
	default:
		if strings.HasPrefix(f.GoType, "*") {
			modelPtr := f.ModelGoType == "" || strings.HasPrefix(f.ModelGoType, "*")
			if modelPtr {
				sb.WriteString(fmt.Sprintf(ind+"if body.%s != nil {\n"+ind+"\tupdates[\"%s\"] = body.%s\n"+ind+"}\n", gn, j, gn))
			} else {
				sb.WriteString(fmt.Sprintf(ind+"if body.%s != nil {\n"+ind+"\tupdates[\"%s\"] = *body.%s\n"+ind+"}\n", gn, j, gn))
			}
		} else {
			sb.WriteString(fmt.Sprintf(ind+"updates[\"%s\"] = body.%s\n", j, gn))
		}
	}
}

func writeDeleteBody(sb *strings.Builder, b *CrudBundle, pkgAlias, ind string) {
	sb.WriteString(ind + "ids, err := tools.ParseFlexibleIDList(h.C)\n")
	sb.WriteString(ind + "if err != nil || len(ids) == 0 {\n")
	sb.WriteString(ind + "\tresponse.JSON(h.C, 200, response.WithCode(response.CodeUnprocessable, \"ids required\", nil))\n")
	sb.WriteString(ind + "\treturn\n" + ind + "}\n")
	sb.WriteString(fmt.Sprintf(ind+"if err := h.D.DBx(h.C).Where(\"%s IN ?\", ids).Delete(&%s.%s{}).Error; err != nil {\n", b.PrimaryKey, pkgAlias, b.StructName))
	sb.WriteString(ind + "\tresponse.JSON(h.C, 200, response.Fail(\"delete failed\"))\n")
	sb.WriteString(ind + "\treturn\n" + ind + "}\n")
	sb.WriteString(ind + "response.JSON(h.C, 200, response.OK(nil))\n")
}
