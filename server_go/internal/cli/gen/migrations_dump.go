package gen

import (
	"fmt"
	"strings"
	"time"

	"gorm.io/gorm"
)

// DumpSchemaSQL 生成合并 DDL（SHOW CREATE TABLE），含 FOREIGN_KEY_CHECKS 包装；down 为注释形式的 DROP。
func DumpSchemaSQL(db *gorm.DB, tables []string) (string, error) {
	var b strings.Builder
	b.WriteString("-- Generated by fastapp-cli migrate dump\n")
	b.WriteString("-- " + time.Now().Format(time.RFC3339) + "\n\n")
	b.WriteString("SET NAMES utf8mb4;\n")
	b.WriteString("SET FOREIGN_KEY_CHECKS = 0;\n\n")

	for _, tbl := range tables {
		var create string
		row := db.Raw("SHOW CREATE TABLE " + quoteIdent(tbl)).Row()
		var name string
		if err := row.Scan(&name, &create); err != nil {
			return "", fmt.Errorf("SHOW CREATE TABLE %s: %w", tbl, err)
		}
		b.WriteString("-- --------------------------------------------\n")
		b.WriteString("-- Table: ")
		b.WriteString(tbl)
		b.WriteString("\n-- --------------------------------------------\n")
		b.WriteString(create)
		b.WriteString(";\n\n")
	}

	b.WriteString("SET FOREIGN_KEY_CHECKS = 1;\n\n")
	b.WriteString("-- DOWN (manual): drop in reverse dependency order\n")
	for i := len(tables) - 1; i >= 0; i-- {
		t := tables[i]
		b.WriteString("-- DROP TABLE IF EXISTS ")
		b.WriteString(quoteIdent(t))
		b.WriteString(";\n")
	}

	return b.String(), nil
}

func quoteIdent(name string) string {
	name = strings.ReplaceAll(name, "`", "``")
	return "`" + name + "`"
}
